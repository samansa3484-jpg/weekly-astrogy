import {chromium} from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1366,height:1000}});
 await page.goto('http://127.0.0.1:4173/weekly-astrogy/');
 const week=await page.getByLabel('表示したい日付').inputValue();
 const action=page.getByRole('textbox',{name:'action0',exact:true});
 await action.fill('バックアップする予定');
 await page.getByRole('textbox',{name:'night0',exact:true}).fill('ありがとう\n次の一歩へ');
 await page.getByRole('button',{name:'記録のバックアップ',exact:true}).click();
 const downloading=page.waitForEvent('download');
 await page.getByRole('button',{name:'記録をファイルに保存',exact:true}).click();
 const download=await downloading;
 assert.match(download.suggestedFilename(),/^weekly-astrology-\d{4}-\d{2}-\d{2}\.json$/);
 const backup=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 assert.equal(backup.weeks.length,1);assert.equal(backup.weeks[0].week,week);
 assert.deepEqual(backup.weeks[0].data,{action0:'バックアップする予定',night0:'ありがとう\n次の一歩へ'});
 const imported={...backup,weeks:[{week,data:{action0:'ファイルの予定',memo:'読み込み確認'}}]};
 const upload=async(target,value)=>{
  await target.getByLabel('バックアップファイルを選択').setInputFiles({name:'planner.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(value))});
  await target.getByText('1週分の記録',{exact:true}).waitFor();
 };
 await upload(page,imported);
 await page.screenshot({path:'artifacts/backup-preview.png',fullPage:true});
 assert.equal(await action.inputValue(),'バックアップする予定');
 await page.getByRole('button',{name:'この内容で読み込む',exact:true}).click();
 await page.getByText('1週分の記録を更新しました。',{exact:true}).waitFor();
 assert.equal(await action.inputValue(),'バックアップする予定');
 assert.equal(await page.getByRole('textbox',{name:'memo',exact:true}).inputValue(),'読み込み確認');
 await upload(page,imported);
 await page.getByRole('radio',{name:'ファイルの記録を優先して上書き',exact:true}).check();
 assert.ok(await page.getByRole('button',{name:'この内容で読み込む',exact:true}).isDisabled());
 await page.getByRole('checkbox',{name:'同じ項目の記録が置き換わることを確認しました',exact:true}).check();
 await page.getByRole('button',{name:'この内容で読み込む',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[aria-label="action0"]').value==='ファイルの予定');
 await page.getByLabel('バックアップファイルを選択').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"bad":true}')});
 await page.getByText(/この手帳のバックアップファイルを選んでください/).waitFor();
 assert.equal(await page.getByRole('button',{name:'この内容で読み込む',exact:true}).count(),0);
 assert.equal(await action.inputValue(),'ファイルの予定');
 await page.screenshot({path:'artifacts/backup-dialog.png',fullPage:true});
 await page.emulateMedia({media:'print'});
 assert.equal(await page.locator('.backup-dialog').isVisible(),false);
 await page.pdf({path:'artifacts/backup-dialog-hidden.pdf',format:'A4',landscape:true,printBackground:true,preferCSSPageSize:true});
 const fresh=await browser.newPage();
 await fresh.goto('http://127.0.0.1:4173/weekly-astrogy/');
 await fresh.getByRole('button',{name:'記録のバックアップ',exact:true}).click();
 await upload(fresh,backup);
 await fresh.getByRole('button',{name:'この内容で読み込む',exact:true}).click();
 await fresh.getByText('1週分の記録を更新しました。',{exact:true}).waitFor();
 await fresh.getByRole('button',{name:'閉じる',exact:true}).click();
 assert.equal(await fresh.getByRole('textbox',{name:'action0',exact:true}).inputValue(),'バックアップする予定');
 assert.equal(await fresh.getByRole('textbox',{name:'night0',exact:true}).inputValue(),'ありがとう\n次の一歩へ');
 console.log('PASS: real JSON download, preview, safe merge, confirmed overwrite, invalid-file protection, fresh-browser restore, print dialog hidden');
}finally{await browser.close()}
